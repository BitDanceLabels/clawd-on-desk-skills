const LANGS = ["vi", "en", "zh"];
const DEFAULT_LANG = "vi";
// Bumped in 0.12.0: older prefs saved "en" only because it was the default, so they move to Vietnamese once.
const LANG_PREFS_VERSION = 2;

function normalizeLang(lang) {
  return LANGS.includes(lang) ? lang : DEFAULT_LANG;
}

// prefs → language to use. Before 0.12.0 "en" was just the default, so it becomes "vi";
// "zh" was always a deliberate choice and is kept. From 0.12.0 on, the saved choice wins.
function langFromPrefs(prefs) {
  if (!prefs || typeof prefs !== "object") return DEFAULT_LANG;
  if ((prefs.langV || 0) >= LANG_PREFS_VERSION) return normalizeLang(prefs.lang);
  return prefs.lang === "zh" ? "zh" : DEFAULT_LANG;
}

function translate(lang, key) {
  return (i18n[normalizeLang(lang)])[key] || i18n.en[key] || i18n[DEFAULT_LANG][key] || key;
}

module.exports = { i18n, LANGS, DEFAULT_LANG, LANG_PREFS_VERSION, normalizeLang, langFromPrefs, translate };
